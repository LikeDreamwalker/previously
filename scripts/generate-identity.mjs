/**
 * Bundle the agent's constitution (identity/agent/CHARTER.md) into a
 * TypeScript module so it's compiled into the build — never read from disk
 * at runtime.
 *
 * This is what makes the agent's identity immutable while it's running: the
 * deployment carries a frozen copy, so a bad edit or a mistaken agent write
 * to the repo can't change the live prompt (and the file sits outside the
 * tool whitelist, so the agent can't touch it at all).
 *
 * Runs via the predev/prebuild hooks in package.json. Re-run manually after
 * editing CHARTER.md:  node scripts/generate-identity.mjs
 */
import { readFileSync, writeFileSync } from "fs";
import { join } from "path";

const root = process.cwd();

const CHARTER_MD = readFileSync(join(root, "identity/agent/CHARTER.md"), "utf-8");

const out = `// AUTO-GENERATED by scripts/generate-identity.mjs — do NOT edit by hand.
// Source of truth: identity/agent/CHARTER.md. Bundled into the build so the
// agent's constitution is immutable at runtime.
export const CHARTER_MD = ${JSON.stringify(CHARTER_MD)};
`;

const target = "src/lib/identity/agent-prompt.generated.ts";
writeFileSync(join(root, target), out);
console.log(`[identity] generated ${target}`);
